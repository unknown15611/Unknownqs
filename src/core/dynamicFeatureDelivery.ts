/**
 * Validates the developer master signature on a dynamic feature module
 * before Android loads its split dex/classes into runtime memory.
 */
export function verifyDynamicModuleSignature(module: FeatureModule): boolean {
  if (!module.isOfficialSigned) return false;
  // Signatures must be valid 40+ hex characters generated by Master Key (@Qaidi156)
  return module.signatureHex.length >= 32;
}

/**
 * Calculates total bandwidth saved by downloading dynamic feature modules
 * instead of full app updates (assuming base APK is ~4.8 MB).
 */
export function calculateBandwidthSavings(module: FeatureModule, baseApkSizeKb: number = 4915): {
  bandwidthSavedKb: number;
  percentageSaved: number;
} {
  const saved = Math.max(0, baseApkSizeKb - module.sizeKb);
  const pct = Math.round((saved / baseApkSizeKb) * 100);
  return {
    bandwidthSavedKb: saved,
    percentageSaved: pct,
  };
}

/**
 * Simulates requesting and installing a feature module from a nearby peer.
 */
export function installFeatureModule(
  modules: FeatureModule[],
  moduleId: string
): { updatedModules: FeatureModule[]; success: boolean; error?: string } {
  const target = modules.find(m => m.id === moduleId);
  if (!target) {
    return { updatedModules: modules, success: false, error: 'Module not found' };
  }

  if (target.isInstalled) {
    return { updatedModules: modules, success: true };
  }

  if (!verifyDynamicModuleSignature(target)) {
    return { updatedModules: modules, success: false, error: 'Invalid module signature' };
  }

  const updated = modules.map(m => (m.id === moduleId ? { ...m, isInstalled: true, downloadProgressPct: 100 } : m));
  return { updatedModules: updated, success: true };
}
